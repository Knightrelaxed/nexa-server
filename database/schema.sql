-- ==========================================
-- 7. Table Transaksi Tertunda (Digunakan saat server restart untuk recovery)
CREATE TABLE IF NOT EXISTS nexa_pending_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  composite_key TEXT NOT NULL UNIQUE,
  tx_data JSONB NOT NULL,
  telegram_sent BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 8. Table Log Perilaku (Melacak rutinitas harian untuk insight proaktif)
-- Jalankan SQL ini di Supabase SQL Editor sebelum deploy.
CREATE TABLE IF NOT EXISTS nexa_behavior_log (
  id          BIGSERIAL PRIMARY KEY,
  event_type  TEXT NOT NULL,      -- 'WAKE_UP' | 'MOOD_DETECTED' | 'FINANCE_RECORD' | dll
  event_data  JSONB DEFAULT '{}', -- Payload konteks spesifik per event_type
  day_of_week INT,                -- 0=Minggu ... 6=Sabtu (waktu Jakarta)
  hour_of_day INT,                -- 0-23 (waktu Jakarta)
  created_at  TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_behavior_log_type ON nexa_behavior_log(event_type);
CREATE INDEX IF NOT EXISTS idx_behavior_log_created ON nexa_behavior_log(created_at);
CREATE INDEX IF NOT EXISTS idx_behavior_log_day_hour ON nexa_behavior_log(day_of_week, hour_of_day);


